#!/usr/bin/env node
// Install the WebdriverIO toolchain the export tests run generated WDIO specs with —
// WITHOUT touching package.json: everything lands in
// node_modules/.cache/locatra-e2e/wdio (its own tiny package.json + node_modules).
//
//   node scripts/e2e/setup-webdriverio.mjs          # install / update to the pins below
//   node scripts/e2e/setup-webdriverio.mjs --check  # exit 0 when installed at the pins
//
// The versions are pinned so a run is reproducible and CI can cache the directory
// keyed on this file's hash. WebdriverIO v9 + Mocha; @wdio/cli brings tsx, which
// WDIO uses to load TypeScript specs. typescript + @types/* are for the strict
// type-check of generated TS (tests/codegen-wdio.test.mjs uses them when present).
// The ChromeDriver that matches the browser is downloaded by WebdriverIO itself
// on first run (into its cache), so nothing else is needed here.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const WDIO_DIR = join(ROOT, 'node_modules/.cache/locatra-e2e/wdio');

export const WDIO_PACKAGES = {
  '@wdio/cli': '9.32.0',
  '@wdio/local-runner': '9.32.0',
  '@wdio/mocha-framework': '9.32.0',
  '@wdio/spec-reporter': '9.32.0',
  '@wdio/globals': '9.31.3',
  '@wdio/types': '9.32.0',
  webdriverio: '9.32.0',
  'expect-webdriverio': '6.1.0',
  typescript: '5.9.3',
  '@types/mocha': '10.0.10',
  '@types/node': '22.20.5',
};

/** Missing or mismatched packages in the cache directory (empty when ready). */
export function wdioMissing(dir = WDIO_DIR) {
  const out = [];
  for (const [name, version] of Object.entries(WDIO_PACKAGES)) {
    const pkg = join(dir, 'node_modules', name, 'package.json');
    if (!existsSync(pkg)) out.push(`${name} (not installed)`);
    else if (JSON.parse(readFileSync(pkg, 'utf8')).version !== version) out.push(`${name} (not ${version})`);
  }
  return out;
}

function main(argv) {
  if (argv.includes('--check')) {
    const missing = wdioMissing();
    if (missing.length) {
      console.log(`WebdriverIO toolchain incomplete: ${missing.join(', ')}`);
      return 1;
    }
    console.log(`WebdriverIO toolchain ready in ${WDIO_DIR}`);
    return 0;
  }
  mkdirSync(WDIO_DIR, { recursive: true });
  writeFileSync(
    join(WDIO_DIR, 'package.json'),
    JSON.stringify(
      {
        name: 'locatra-e2e-wdio',
        private: true,
        description: 'Generated by scripts/e2e/setup-webdriverio.mjs — not part of the extension.',
        type: 'module',
        dependencies: WDIO_PACKAGES,
      },
      null,
      2
    ) + '\n'
  );
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const res = spawnSync(npm, ['install', '--no-audit', '--no-fund', '--loglevel', 'error'], {
    cwd: WDIO_DIR,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (res.status !== 0) {
    console.error(`npm install failed in ${WDIO_DIR}`);
    return res.status || 1;
  }
  const missing = wdioMissing();
  if (missing.length) {
    console.error(`installed, but still missing: ${missing.join(', ')}`);
    return 1;
  }
  console.log(`WebdriverIO toolchain ready in ${WDIO_DIR}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
