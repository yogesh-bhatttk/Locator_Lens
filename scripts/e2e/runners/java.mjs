// Export runners for the Java targets (src/codegen-java.js): Playwright for Java and
// Selenium for Java, both JUnit 5. Loaded by scripts/e2e/run-exports.mjs ("runner
// plugins").
//
// The generated test class is written UNMODIFIED into a throwaway Maven project
// (pom.xml from scripts/e2e/setup-java.mjs) and run with `mvn test`, exactly as a user
// would. Only the browser launch is pointed at the shared Chromium (LOCATRA_CHROMIUM),
// headless, from outside the file:
//   * Playwright for Java runs its bundled Node driver; NODE_OPTIONS preloads a hook
//     into that driver which fills in `executablePath` for chromium launches that set
//     none (the same thing playwright.config's launchOptions do for the Node runner).
//     PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD stops it fetching its own browser build.
//   * Selenium for Java: Selenium Manager takes the browser from SE_BROWSER_PATH,
//     which points at a small wrapper that starts LOCATRA_CHROMIUM headless (Chrome
//     reads no flags from the environment). Stray chromedrivers on PATH are hidden so
//     Selenium Manager resolves the one matching that browser.
//
// Both record each browser launch in LOCATRA_LAUNCH_LOG, and a run that never
// launched LOCATRA_CHROMIUM fails: a machine with Google Chrome installed (every
// GitHub runner) would otherwise pass silently on the wrong browser.
//
// The JDK and Maven come from setup-java.mjs (JAVA_HOME / PATH, or its cache).

import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { delimiter, join } from 'node:path';
import process from 'node:process';

import { javaEnv, javaToolchain, mvnArgs, pomXml } from '../setup-java.mjs';

// Loaded into the Playwright driver (node) by NODE_OPTIONS=--require. The driver's
// server-side BrowserType is patched once it is loaded: a chromium launch without an
// explicit executablePath uses LOCATRA_CHROMIUM.
const PLAYWRIGHT_DRIVER_HOOK = `// Generated by scripts/e2e/runners/java.mjs.
'use strict';
const fs = require('node:fs');
const Module = require('node:module');
const PATCHED = Symbol.for('locatra.executablePath');
const load = Module._load;
Module._load = function locatraLoad(request, parent, isMain) {
  const exported = load.apply(this, arguments);
  const BrowserType = exported && /(^|[\\\\/])browserType(\\.js)?$/.test(request) ? exported.BrowserType : null;
  if (BrowserType && typeof BrowserType.prototype._innerLaunch === 'function' && !BrowserType.prototype[PATCHED]) {
    const inner = BrowserType.prototype._innerLaunch;
    BrowserType.prototype._innerLaunch = function (progress, options, ...rest) {
      const exe = process.env.LOCATRA_CHROMIUM;
      if (exe && this._name === 'chromium' && options && !options.executablePath) {
        options = { ...options, executablePath: exe };
      }
      if (process.env.LOCATRA_LAUNCH_LOG && options) {
        const mode = options.headless === false ? 'headed' : 'headless';
        fs.appendFileSync(process.env.LOCATRA_LAUNCH_LOG, (options.executablePath || this._name) + ' ' + mode + '\\n');
      }
      return inner.call(this, progress, options, ...rest);
    };
    BrowserType.prototype[PATCHED] = true;
  }
  return exported;
};
`;

/** A shell wrapper that runs LOCATRA_CHROMIUM headless with the harness's usual flags. */
function chromeWrapper(chromium) {
  const headless = process.env.LOCATRA_E2E_HEADED === '1' ? '' : ' --headless=new';
  return `#!/bin/sh
# Generated by scripts/e2e/runners/java.mjs: the browser Selenium Manager hands to
# ChromeDriver (SE_BROWSER_PATH).
if [ "$1" = "--version" ]; then exec ${JSON.stringify(chromium)} --version; fi
if [ -n "$LOCATRA_LAUNCH_LOG" ]; then echo ${JSON.stringify(`${chromium}${headless ? ' headless' : ' headed'}`)} >> "$LOCATRA_LAUNCH_LOG"; fi
exec ${JSON.stringify(chromium)} --no-sandbox --disable-dev-shm-usage --window-size=1280,900${headless} "$@"
`;
}

/** The public class name a generated file declares (the file must carry it). */
function className(script) {
  const m = /^(?:public\s+|final\s+)*class\s+([A-Za-z_$][\w$]*)/m.exec(script);
  return m ? m[1] : 'RecordedTest';
}

function writeProject(dir, kind, script) {
  const src = join(dir, 'src/test/java');
  mkdirSync(src, { recursive: true });
  writeFileSync(join(dir, 'pom.xml'), pomXml(kind));
  const file = join(src, `${className(script)}.java`);
  writeFileSync(file, script);
  return file;
}

// Small heaps: Maven and the forked test JVM share the machine with Chromium.
const JVM_OPTS = '-Xmx512m -XX:+UseSerialGC';

/**
 * `mvn test` in `dir`. When `verifyLaunch`, a passing run must also have launched
 * LOCATRA_CHROMIUM (per LOCATRA_LAUNCH_LOG), headless unless LOCATRA_E2E_HEADED=1.
 */
async function mavenTest(tools, tc, dir, env, { verifyLaunch = true } = {}) {
  const log = join(dir, 'browser-launches.log');
  const result = await tools.run(tc.mvn, mvnArgs('test', `-DargLine=${JVM_OPTS}`), {
    cwd: dir,
    env: javaEnv(tc, { ...env, MAVEN_OPTS: JVM_OPTS, LOCATRA_LAUNCH_LOG: log }),
    timeout: 420_000,
    unset: ['CHROMEWEBDRIVER'],
  });
  if (!verifyLaunch || result.code !== 0) return result;
  const launches = existsSync(log) ? readFileSync(log, 'utf8').trim().split('\n').filter(Boolean) : [];
  const want = `${env.LOCATRA_CHROMIUM} ${process.env.LOCATRA_E2E_HEADED === '1' ? 'headed' : 'headless'}`;
  if (!launches.length || launches.some((l) => l !== want)) {
    const seen = launches.length ? launches.join(', ') : 'none';
    return {
      ...result,
      code: 1,
      output: `${result.output}\n[locatra] expected every browser launch to be "${want}"; saw: ${seen}\n`,
    };
  }
  return result;
}

function playwrightJava(tools) {
  return async ({ dir, script, env }) => {
    const tc = javaToolchain();
    if (tc.missing) return { skip: tc.missing };
    writeProject(dir, 'playwright', script);
    const hook = join(dir, 'locatra-driver-hook.cjs');
    writeFileSync(hook, PLAYWRIGHT_DRIVER_HOOK);
    const runEnv = {
      ...env,
      PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD: '1',
      NODE_OPTIONS: `--require ${JSON.stringify(hook)}`,
    };
    return { result: await mavenTest(tools, tc, dir, runEnv) };
  };
}

function seleniumJava(tools) {
  return async ({ dir, script, env }) => {
    const tc = javaToolchain();
    if (tc.missing) return { skip: tc.missing };
    writeProject(dir, 'selenium', script);
    let browser = env.LOCATRA_CHROMIUM;
    if (process.platform !== 'win32') {
      browser = join(dir, 'chromium-headless.sh');
      writeFileSync(browser, chromeWrapper(env.LOCATRA_CHROMIUM));
      chmodSync(browser, 0o755);
    }
    const runEnv = tools.withoutStrayChromedriver({ ...env, SE_BROWSER_PATH: browser });
    if (process.env.LOCATRA_CHROMEDRIVER) {
      runEnv.PATH = [join(process.env.LOCATRA_CHROMEDRIVER, '..'), runEnv.PATH].join(delimiter);
    }
    return {
      result: await mavenTest(tools, tc, dir, runEnv, { verifyLaunch: process.platform !== 'win32' }),
    };
  };
}

export const runners = {
  'playwright-java': playwrightJava,
  'selenium-java': seleniumJava,
};
