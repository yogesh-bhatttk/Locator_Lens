// Export-test runners for the C# targets (src/codegen-csharp.js):
//   playwright-csharp  Microsoft.Playwright.NUnit (PageTest) under `dotnet test`
//   selenium-csharp    Selenium.WebDriver 4 + NUnit under `dotnet test`
//
// The generated RecordedTest.cs is written UNMODIFIED into a throwaway test project
// (a .csproj with the packages a user would reference); only the browser launch is
// pointed at the shared Chromium (LOCATRA_CHROMIUM), headless:
//   * Playwright: a .runsettings file (Playwright → LaunchOptions → ExecutablePath,
//     Headless) — the standard Microsoft.Playwright.NUnit configuration channel.
//   * Selenium: `new ChromeDriver()` asks Selenium Manager for a browser and driver;
//     SE_BROWSER_PATH hands it a tiny wrapper that starts LOCATRA_CHROMIUM headless
//     (sandbox-free, fixed window size, like the JS preload / Python sitecustomize),
//     and Selenium Manager fetches the ChromeDriver that matches that browser (a
//     stray driver on PATH is hidden, as for the other Selenium runners).
//
// The .NET SDK comes from PATH / DOTNET_ROOT / LOCATRA_DOTNET or the local cache that
// `node scripts/e2e/setup-csharp.mjs` installs; NuGet packages are cached in
// node_modules/.cache/locatra-e2e/nuget unless NUGET_PACKAGES is set.

import { chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

import { dotnetEnv, findDotnet } from '../setup-csharp.mjs';

/** Package versions the scaffold references (Playwright matches @playwright/test). */
export const PACKAGES = {
  common: [
    ['Microsoft.NET.Test.Sdk', '18.0.1'],
    ['NUnit', '4.4.0'],
    ['NUnit3TestAdapter', '5.2.0'],
  ],
  playwright: [['Microsoft.Playwright.NUnit', '1.59.0']],
  selenium: [
    ['Selenium.WebDriver', '4.51.0'],
    ['Selenium.Support', '4.51.0'],
  ],
};

const xml = (s) =>
  String(s).replace(
    /[<>&"']/g,
    (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' })[c]
  );

/**
 * The project file: ImplicitUsings off, so the generated file must bring every
 * `using` it needs; nullable on and warnings as errors, so it must also compile
 * cleanly under the strictest common settings.
 */
export function csproj({ major, kinds }) {
  const refs = [...PACKAGES.common];
  for (const k of kinds) refs.push(...PACKAGES[k]);
  return `<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by scripts/e2e/runners/csharp.mjs -->
  <PropertyGroup>
    <TargetFramework>net${major}.0</TargetFramework>
    <ImplicitUsings>disable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <LangVersion>latest</LangVersion>
    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
    <IsPackable>false</IsPackable>
    <IsTestProject>true</IsTestProject>
    <NuGetAudit>false</NuGetAudit>
    <SatelliteResourceLanguages>en</SatelliteResourceLanguages>
  </PropertyGroup>
  <ItemGroup>
${refs.map(([id, v]) => `    <PackageReference Include="${id}" Version="${v}" />`).join('\n')}
  </ItemGroup>
</Project>
`;
}

/** Playwright for .NET reads its launch options from the run settings. */
export function runsettings({ chromium, headed }) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/e2e/runners/csharp.mjs -->
<RunSettings>
  <Playwright>
    <BrowserName>chromium</BrowserName>
    <ExpectTimeout>10000</ExpectTimeout>
    <LaunchOptions>
      <Headless>${headed ? 'false' : 'true'}</Headless>
${chromium ? `      <ExecutablePath>${xml(chromium)}</ExecutablePath>\n` : ''}    </LaunchOptions>
  </Playwright>
</RunSettings>
`;
}

/** File the wrapper touches when ChromeDriver starts the browser through it. */
export const LAUNCH_MARKER = 'locatra-chromium.launched';

const sh = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

/**
 * A launcher Selenium Manager accepts as the browser: Chromium, headless. It leaves
 * a marker when ChromeDriver starts a session through it (not for Selenium Manager's
 * \`--version\` probe), so the runner can prove the run never fell back to another
 * browser installed on the machine.
 */
export function chromeWrapper({ chromium, headed, marker }) {
  const args = ['--no-sandbox', '--disable-dev-shm-usage', '--window-size=1280,900'];
  if (!headed) args.push('--headless=new');
  return `#!/bin/sh
# Generated by scripts/e2e/runners/csharp.mjs: start the shared Chromium the way the
# other Selenium runners do (headless, no sandbox, fixed window size).
case "$1" in --version|-version) ;; *) : > ${sh(marker)} ;; esac
exec ${sh(chromium)} ${args.join(' ')} "$@"
`;
}

/** Lay out the test project around `script` (written byte-for-byte). */
export function scaffold({ dir, kind, major, script, chromium, headed = false }) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'Locatra.Recorded.csproj'), csproj({ major, kinds: [kind] }));
  writeFileSync(join(dir, 'RecordedTest.cs'), script);
  if (kind === 'playwright')
    writeFileSync(join(dir, 'locatra.runsettings'), runsettings({ chromium, headed }));
  if (kind === 'selenium' && chromium && process.platform !== 'win32') {
    const wrapper = join(dir, 'locatra-chromium.sh');
    rmSync(join(dir, LAUNCH_MARKER), { force: true });
    writeFileSync(wrapper, chromeWrapper({ chromium, headed, marker: join(dir, LAUNCH_MARKER) }));
    chmodSync(wrapper, 0o755);
    return { browserPath: wrapper };
  }
  // Windows cannot launch a shell wrapper as the browser: hand over Chromium itself.
  return { browserPath: chromium || null };
}

function dotnetRunner(kind) {
  return ({ run, withoutStrayChromedriver }) =>
    async ({ dir, script, env }) => {
      const found = findDotnet();
      if (!found) {
        return {
          skip: '.NET SDK (8 or newer) not found — run `node scripts/e2e/setup-csharp.mjs` (installs it into node_modules/.cache/locatra-e2e/dotnet without sudo)',
        };
      }
      const headed = process.env.LOCATRA_E2E_HEADED === '1';
      const { browserPath } = scaffold({
        dir,
        kind,
        major: found.major,
        script,
        chromium: env.LOCATRA_CHROMIUM,
        headed,
      });
      let runEnv = { ...env, ...dotnetEnv(found) };
      const args = ['test', '--nologo', '--logger', 'console;verbosity=normal'];
      if (kind === 'playwright') {
        args.push('--settings', 'locatra.runsettings');
      } else {
        if (browserPath) runEnv.SE_BROWSER_PATH = browserPath;
        runEnv = withoutStrayChromedriver(runEnv);
      }
      const result = await run(found.dotnet, args, {
        cwd: dir,
        env: runEnv,
        timeout: 600_000,
        unset: kind === 'selenium' ? ['CHROMEWEBDRIVER'] : [],
      });
      if (kind === 'selenium' && browserPath && browserPath !== env.LOCATRA_CHROMIUM) {
        if (!existsSync(join(dir, LAUNCH_MARKER)) && result.code === 0) {
          result.code = 1;
          result.output += `\n[locatra] Selenium did not start the browser through ${browserPath} — SE_BROWSER_PATH was ignored, so another browser ran\n`;
        }
      }
      return { result };
    };
}

export const runners = {
  'playwright-csharp': dotnetRunner('playwright'),
  'selenium-csharp': dotnetRunner('selenium'),
};
