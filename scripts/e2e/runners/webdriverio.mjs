// Runner plugin for scripts/e2e/run-exports.mjs: runs the exported WebdriverIO v9
// spec (TypeScript or JavaScript) with the real WDIO testrunner + Mocha, exactly as
// exported. Only a project scaffold is written around it:
//   package.json   { "type": "module" } — the spec uses ES-module imports
//   node_modules   a link to the toolchain scripts/e2e/setup-webdriverio.mjs installs
//                  into node_modules/.cache/locatra-e2e/wdio (package.json untouched)
//   tsconfig.json  (TypeScript) the WDIO starter's compiler options + strict; the spec
//                  must pass `tsc --noEmit` before it runs
//   wdio.conf.js   Chrome capability pointed at LOCATRA_CHROMIUM, headless unless
//                  LOCATRA_E2E_HEADED=1
//
// ChromeDriver: WebdriverIO resolves (and caches) the one matching that browser
// itself, into node_modules/.cache/locatra-e2e/wdio/drivers. It never looks at PATH,
// but CHROMEDRIVER_PATH would override it, so that (and the CI runners'
// CHROMEWEBDRIVER) is cleared; SE_SKIP_DRIVER_IN_PATH is set too, for consistency.
// LOCATRA_CHROMEDRIVER, when set, is used explicitly.

import { existsSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

import { WDIO_DIR, wdioMissing } from '../setup-webdriverio.mjs';

const SETUP_HINT = 'run `node scripts/e2e/setup-webdriverio.mjs`';

/** The scaffold's tsconfig: WDIO's starter options, plus strict. */
export const WDIO_TSCONFIG = {
  compilerOptions: {
    target: 'es2022',
    module: 'esnext',
    moduleResolution: 'bundler',
    strict: true,
    noEmit: true,
    skipLibCheck: true,
    types: ['node', '@wdio/globals/types', 'expect-webdriverio', '@wdio/mocha-framework'],
  },
};

export function wdioConfig(spec) {
  return `// Generated by scripts/e2e/runners/webdriverio.mjs.
import process from 'node:process';

const args = ['--no-sandbox', '--disable-dev-shm-usage', '--window-size=1280,900'];
if (process.env.LOCATRA_E2E_HEADED !== '1') args.push('--headless=new');

const capability = {
  browserName: 'chrome',
  'goog:chromeOptions': { binary: process.env.LOCATRA_CHROMIUM, args },
};
if (process.env.LOCATRA_CHROMEDRIVER) {
  capability['wdio:chromedriverOptions'] = { binary: process.env.LOCATRA_CHROMEDRIVER };
}

export const config = {
  runner: 'local',
  specs: [${JSON.stringify(`./${spec}`)}],
  maxInstances: 1,
  capabilities: [capability],
  logLevel: 'warn',
  autoXvfb: false,
  bail: 0,
  waitforTimeout: 10000,
  connectionRetryTimeout: 120000,
  connectionRetryCount: 1,
  framework: 'mocha',
  reporters: ['spec'],
  mochaOpts: { ui: 'bdd', timeout: 120000 },
};
`;
}

function webdriverio(lang) {
  return ({ run, withoutStrayChromedriver }) =>
    async ({ dir, script, env }) => {
      const missing = wdioMissing();
      if (missing.length) {
        return { skip: `WebdriverIO is not installed (${missing.join(', ')}) — ${SETUP_HINT}` };
      }
      const ts = lang === 'typescript';
      const spec = `recorded.e2e.${ts ? 'ts' : 'js'}`;
      writeFileSync(join(dir, spec), script);
      writeFileSync(join(dir, 'package.json'), '{ "type": "module" }\n');
      writeFileSync(join(dir, 'wdio.conf.js'), wdioConfig(spec));
      const modules = join(dir, 'node_modules');
      if (!existsSync(modules)) symlinkSync(join(WDIO_DIR, 'node_modules'), modules, 'junction');

      const runEnv = withoutStrayChromedriver({
        ...env,
        WEBDRIVER_CACHE_DIR: join(WDIO_DIR, 'drivers'),
        NO_COLOR: '1',
        FORCE_COLOR: '0',
      });
      const unset = ['CHROMEWEBDRIVER', 'CHROMEDRIVER_PATH', 'ELECTRON_RUN_AS_NODE'];

      if (ts) {
        writeFileSync(
          join(dir, 'tsconfig.json'),
          JSON.stringify({ ...WDIO_TSCONFIG, include: [spec] }, null, 2)
        );
        const tsc = join(WDIO_DIR, 'node_modules/typescript/bin/tsc');
        const typed = await run(process.execPath, [tsc, '-p', 'tsconfig.json'], {
          cwd: dir,
          env: runEnv,
          unset,
        });
        if (typed.code !== 0) {
          return { result: { ...typed, output: `tsc --noEmit failed:\n${typed.output}` } };
        }
      }

      const cli = join(WDIO_DIR, 'node_modules/@wdio/cli/bin/wdio.js');
      return {
        result: await run(process.execPath, [cli, 'run', 'wdio.conf.js'], {
          cwd: dir,
          env: runEnv,
          timeout: 300_000,
          unset,
        }),
      };
    };
}

export const runners = {
  'webdriverio-typescript': webdriverio('typescript'),
  'webdriverio-javascript': webdriverio('javascript'),
};
